'use strict';
// Fetch the live repo list from GitHub (authed) and write a JS array to docs/fallback-repos.js.
// The browser falls back to this list if the unauthenticated GitHub API hits a rate limit.
// Run: node scripts/gen-fallback.js (requires `gh` on PATH, authenticated).

const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');

// Fetch raw JSON (no jq filter - avoid Windows shell quoting hell).
const r = spawnSync('gh', ['api', 'users/Laufbursche42/repos?per_page=100&sort=updated'], { encoding: 'utf8', shell: false });
if (r.status !== 0) { console.error('gh api failed:', r.stderr); process.exit(1); }
const data = JSON.parse(r.stdout);

const repos = data
  .filter(x => !x.fork && x.name !== 'Laufbursche42')
  .sort((a, b) => a.name.localeCompare(b.name))
  .map(x => ({
    name: x.name,
    description: x.description || '',
    language: x.language || '',
    stargazers_count: x.stargazers_count || 0,
    hasPages: !!x.has_pages,
    homepage: x.homepage || '',
    archived: !!x.archived
  }));

const out = '// GENERATED by scripts/gen-fallback.js from the live GitHub API - do not edit by hand.\n' +
  '// Rebuilt on every commit that touches repo metadata so an API rate-limit does not shrink the list.\n' +
  'window.FALLBACK_REPOS = ' + JSON.stringify(repos, null, 2) + ';\n';
const outPath = path.resolve(__dirname, '../docs/fallback-repos.js');
fs.writeFileSync(outPath, out);
console.log('wrote ' + outPath + ' - ' + repos.length + ' repos');
