'use strict';
// Fetch the live repo list + release downloads from GitHub (authed via gh / GITHUB_TOKEN)
// and write a JS array to docs/fallback-repos.js. The browser then shows live data without
// hitting the unauth 60/h rate limit. Rebuilt on a cron + on every push by a GH Action.
//
// Run: node scripts/gen-fallback.js
// Requires: `gh` on PATH, authenticated (locally via `gh auth login`, in CI via GITHUB_TOKEN).

const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');

function ghApi(url) {
  const r = spawnSync('gh', ['api', url, '--paginate'], { encoding: 'utf8', shell: false, maxBuffer: 64 * 1024 * 1024 });
  if (r.status !== 0) throw new Error('gh api ' + url + ' failed: ' + r.stderr);
  return JSON.parse(r.stdout.replace(/\]\s*\[/g, ','));  // concatenate paginated arrays
}

// --- release helpers (mirror of docs/app.js so the output needs no post-processing) --------
const PLAT_MATCH = {
  apk:   (n) => n.endsWith('.apk'),
  win:   (n) => n.endsWith('.exe') || n.endsWith('.msi') || /(^|[-_.])win(dows|64|32)?([-_.]|$)/.test(n),
  mac:   (n) => n.endsWith('.dmg') || n.endsWith('.pkg') || /(^|[-_.])(mac(os)?|osx|darwin)([-_.]|$)/.test(n),
  linux: (n) => n.endsWith('.appimage') || n.endsWith('.deb') || n.endsWith('.rpm') || /(^|[-_.])linux([-_.]|$)/.test(n)
};
function isAppAsset(name) { const n = (name || '').toLowerCase(); return PLAT_MATCH.apk(n) || PLAT_MATCH.win(n) || PLAT_MATCH.mac(n) || PLAT_MATCH.linux(n); }
function sumDownloads(releases) {
  let total = 0;
  (releases || []).forEach((rel) => (rel.assets || []).forEach((a) => {
    if (isAppAsset(a.name) && typeof a.download_count === 'number') total += a.download_count;
  }));
  return total;
}
function classifyAssets(assets) {
  const out = {};
  (assets || []).forEach((a) => {
    const n = (a.name || '').toLowerCase();
    const url = a.browser_download_url;
    if (!url) return;
    if (!out.apk && PLAT_MATCH.apk(n)) out.apk = url;
    else if (!out.win && PLAT_MATCH.win(n)) out.win = url;
    else if (!out.mac && PLAT_MATCH.mac(n)) out.mac = url;
    else if (!out.linux && PLAT_MATCH.linux(n)) out.linux = url;
  });
  return out;
}

// --- main --------------------------------------------------------------------
const rawRepos = ghApi('users/Laufbursche42/repos?per_page=100&sort=updated');
const base = rawRepos
  .filter((x) => !x.fork && x.name !== 'Laufbursche42')
  .sort((a, b) => a.name.localeCompare(b.name));

const repos = base.map((x) => {
  const r = {
    name: x.name,
    description: x.description || '',
    language: x.language || '',
    stargazers_count: x.stargazers_count || 0,
    hasPages: !!x.has_pages,
    homepage: x.homepage || '',
    archived: !!x.archived,
    downloads: null,
    dlCount: 0
  };
  // Archived repos ship no new downloads; skip the extra API call.
  if (r.archived) return r;
  try {
    const releases = ghApi('repos/Laufbursche42/' + encodeURIComponent(x.name) + '/releases?per_page=100');
    const rel = Array.isArray(releases) && releases.length ? releases[0] : null;
    r.downloads = rel ? classifyAssets(rel.assets) : null;
    r.dlCount = sumDownloads(releases);
  } catch (e) {
    console.warn(x.name + ': releases fetch failed - ' + (e.message || e));
  }
  return r;
});

const out = '// GENERATED by scripts/gen-fallback.js from the GitHub API (authed via gh / GITHUB_TOKEN).\n' +
  '// Rebuilt on cron + on every push by .github/workflows/refresh-roster.yml so the browser\n' +
  '// does not need to call the API at all - no unauth 60/h rate limit for visitors.\n' +
  'window.FALLBACK_REPOS = ' + JSON.stringify(repos, null, 2) + ';\n';
const outPath = path.resolve(__dirname, '../docs/fallback-repos.js');
fs.writeFileSync(outPath, out);
const withDl = repos.filter((r) => r.dlCount > 0).length;
console.log('wrote ' + outPath + ' - ' + repos.length + ' repos (' + withDl + ' with downloads)');
